// Embeds the SQL migrations made by drizzle-kit (./drizzle) into the server code, so they run on the
// first database use in any hosting (no separate migration step). Run by `npm run db:generate`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(web, "drizzle");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const list = files.map((f) => ({
  name: f.replace(/\.sql$/, ""),
  statements: fs.readFileSync(path.join(dir, f), "utf8").split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean),
}));
fs.writeFileSync(
  path.join(web, "src/lib/db/migrations.generated.ts"),
  "// Generated by scripts/embed-migrations.mjs from ./drizzle — do not edit.\n" +
    "export const MIGRATIONS: { name: string; statements: string[] }[] = " + JSON.stringify(list, null, 2) + ";\n",
);
console.log("embedded", files.length, "migration(s)");
