const DICTS: Record<Lang, Partial<Dict>> = { en, fa, ckb };

export type SiteKey = keyof typeof en;

/** A site text in [lang] (Kurdish falls back to Persian for admin texts, then English). */
export function siteText(lang: Lang, key: SiteKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? (lang === "ckb" ? fa[key] : undefined) ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function isLang(x: unknown): x is Lang {
  return x === "en" || x === "fa" || x === "ckb";
}

/** Digits in the language's script (Persian and Kurdish use Eastern Arabic digits). */
export function digits(lang: Lang, value: string | number): string {
  const s = String(value);
  if (lang === "en") return s;
  const map = lang === "fa" ? "۰۱۲۳۴۵۶۷۸۹" : "٠١٢٣٤٥٦٧٨٩";
  return s.replace(/[0-9]/g, (d) => map[Number(d)]);
}
